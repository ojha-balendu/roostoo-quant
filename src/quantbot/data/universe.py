"""Mapping between Roostoo pairs ("BTC/USD") and Binance symbols ("BTCUSDT")."""

from __future__ import annotations

from pathlib import Path

import yaml

from quantbot.exchange.models import PairInfo


def default_symbol(coin: str, quote: str = "USDT") -> str:
    return f"{coin.upper()}{quote}"


def build_universe(
    pairs: dict[str, PairInfo],
    overrides: dict[str, str | None] | None = None,
    existing: dict[str, str | None] | None = None,
) -> dict[str, str | None]:
    """Overrides win, then entries already in the file (manual edits), then COIN+USDT."""
    overrides, existing = overrides or {}, existing or {}
    out: dict[str, str | None] = {}
    for pair in sorted(pairs):
        if pair in overrides:
            out[pair] = overrides[pair]
        elif pair in existing:
            out[pair] = existing[pair]
        else:
            out[pair] = default_symbol(pairs[pair].coin)
    return out


def read_universe_file(path: str | Path) -> dict[str, str | None]:
    path = Path(path)
    if not path.exists():
        return {}
    raw = yaml.safe_load(path.read_text()) or {}
    return dict(raw.get("pairs") or {})


def load_universe(path: str | Path) -> dict[str, str]:
    """Only pairs with Binance data (null entries dropped)."""
    return {p: s for p, s in read_universe_file(path).items() if s}


def save_universe(path: str | Path, mapping: dict[str, str | None], pairs: dict[str, PairInfo] | None = None) -> None:
    lines = [
        "# Roostoo pair -> Binance symbol. Generated by `quantbot universe`; manual edits are preserved.",
        "# Set a symbol to null when Binance has no data for it (e.g. tokenized stocks),",
        "# or fix it when the ticker differs between the two venues.",
        "pairs:",
    ]
    for pair, symbol in mapping.items():
        note = ""
        if pairs and pair in pairs:
            info = pairs[pair]
            note = f"  # {info.full_name}" + ("" if info.can_trade else " (CanTrade=false)")
        lines.append(f'  "{pair}": {symbol if symbol else "null"}{note}')
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text("\n".join(lines) + "\n")
